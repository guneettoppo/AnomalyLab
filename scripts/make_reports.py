"""Build every figure and the machine-checkable report from the benchmark outputs.

Run after scripts/run_benchmark.py:

    python scripts/make_reports.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from anomalylab import plots                                        # noqa: E402
from anomalylab import nab_scoring as ns                            # noqa: E402
from anomalylab.detectors import PCAReconstruction, Consensus, explain  # noqa: E402
from anomalylab.features import calibrated_value, pit_scores, tail_threshold  # noqa: E402
from anomalylab.io import load_labels, load_series                   # noqa: E402

EXAMPLES = [
    "artificialWithAnomaly/art_daily_jumpsup.csv",
    "realKnownCause/machine_temperature_system_failure.csv",
    "realTweets/Twitter_volume_AMZN.csv",
]


def main() -> int:
    reports = ROOT / "reports"
    board = pd.read_csv(ROOT / "outputs" / "leaderboard.csv", keep_default_na=False)
    per_series = pd.read_csv(ROOT / "outputs" / "per_series.csv", keep_default_na=False)
    metrics = json.loads((reports / "metrics.json").read_text())
    q = float(metrics["deployable_quantile"])

    made = []
    made.append(plots.leaderboard(board, reports / "leaderboard.png"))
    made.append(plots.category_heatmap(per_series, reports / "score_heatmap.png"))
    made.append(plots.tradeoff(board, reports / "tradeoff.png"))

    labels = load_labels()
    det = Consensus()
    examples = []
    for key in EXAMPLES:
        s = load_series(key, labels)
        out = det.fit_predict(s)
        pl = s.probation_len()
        score = pit_scores(out.raw, pl)
        thr = tail_threshold(out.raw, pl, q)
        pred = out.raw > thr
        pred[:pl] = False
        examples.append({
            "name": s.name, "ticks": s.ticks, "values": s.values,
            "windows": s.windows, "score": score,
            "hits": np.flatnonzero(pred),
            "threshold": calibrated_value(out.raw, pl, thr),
        })

    made.append(plots.detections(examples, reports / "detections.png"))

    # feature evidence for the strongest PCA alarm on the machine-temperature stream
    s = load_series(EXAMPLES[1], labels)
    pca = PCAReconstruction()
    out = pca.fit_predict(s)
    score = pit_scores(out.raw, s.probation_len())
    score[: s.probation_len()] = 0
    top = int(np.argmax(score))
    why = explain(out, top, 8)
    names = [w[0] for w in why][::-1]
    vals = np.array([w[1] for w in why][::-1])
    stamp = pd.Timestamp(int(s.ticks[top]))
    made.append(plots.evidence(names, vals, reports / "evidence.png",
                              f"PCA reconstruction residuals at the top alarm\n{s.name}  "
                              f"{stamp:%Y-%m-%d %H:%M}  score={score[top]:.3f}"))

    rows = []
    for r in board.itertuples():
        rows.append(f"| `{r.detector}` | {r.nab_score:.2f} | {r.nab_score_deployable:.2f} | "
                    f"{r.mean_average_precision:.3f} | {r.mean_precision:.3f} | "
                    f"{r.mean_recall:.3f} | {r.window_recall * 100:.0f}% | "
                    f"{r.false_alarms_per_day:.2f} |")
    table = ("| detector | NAB score | NAB score @ deployable thr. | mean AP | mean precision | "
             "mean recall | incidents caught | false alarms / stream-day |\n"
             "|---|---|---|---|---|---|---|---|\n" + "\n".join(rows))

    md = f"""# Results

Generated by `scripts/make_reports.py` from `outputs/leaderboard.csv`.
Corpus: {metrics['n_series']} streams, {metrics['n_windows']} labelled windows,
profile `{metrics['profile']}`, deployable quantile {q:g}, runtime {metrics['runtime_seconds']}s.

{table}

![Leaderboard](leaderboard.png)

![Score by stream family](score_heatmap.png)

![Detection quality vs operator load](tradeoff.png)

![Detections](detections.png)

![Feature evidence](evidence.png)
"""
    (reports / "results.md").write_text(md, encoding="utf-8")

    print("figures:")
    for p in made:
        print(f"  {p.relative_to(ROOT)}  ({p.stat().st_size // 1024} KB)")
    print(f"  reports/results.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
